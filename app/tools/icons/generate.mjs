// Turns the Hugeicons glyphs listed in icons.json into Kotlin path data, so the app draws exactly these icons.
// Run from app/: node tools/icons/generate.mjs [path to @hugeicons/core-free-icons]
// Reads an icon package already on disk; downloads nothing.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { normalizePath } from "../path-normalize.mjs";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const pkg = process.argv[2] ?? resolve(app, "node_modules/@hugeicons/core-free-icons");
const iconsDir = resolve(pkg, "dist/esm");
const out = resolve(app, "core/resources/src/commonMain/kotlin/app/kiddo/core/resources/generated/KiddoGlyphs.kt");
const names = JSON.parse(readFileSync(resolve(app, "tools/icons/icons.json"), "utf8"));

// A circle becomes two arcs so every glyph is plain path data.
const circle = ({ cx, cy, r }) => `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`;
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const kstr = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

const entries = [];
for (const [name, file] of Object.entries(names)) {
  const glyph = (await import(pathToFileURL(resolve(iconsDir, `${file}.js`)).href)).default;
  const strokes = glyph.map(([tag, a]) => {
    const d = tag === "circle" ? circle({ cx: +a.cx, cy: +a.cy, r: +a.r }) : a.d;
    return `GlyphStroke(${kstr(normalizePath(d))}, round = ${a.strokeLinecap === "round"}, roundJoin = ${a.strokeLinejoin === "round"})`;
  });
  entries.push(`    ${pascal(name)}(\n        listOf(\n${strokes.map((s) => `            ${s},`).join("\n")}\n        ),\n    ),`);
}

const kotlin = `// Generated by tools/icons/generate.mjs from Hugeicons core-free-icons (MIT). Do not edit by hand.
package app.kiddo.core.resources.generated

public class GlyphStroke(public val pathData: String, public val round: Boolean, public val roundJoin: Boolean)

public enum class KiddoGlyph(public val strokes: List<GlyphStroke>) {
${entries.join("\n")}
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, kotlin);
console.log(`${Object.keys(names).length} glyphs -> ${out}`);
