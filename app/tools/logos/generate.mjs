// Turns the brand SVGs in tools/logos/svg into Kotlin path data, so the app draws each logo with no image files.
// Run from app/: node tools/logos/generate.mjs. Provider marks are LobeHub Icons (MIT); each logo belongs to its owner.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizePath } from "../path-normalize.mjs";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const dir = resolve(app, "tools/logos/svg");
const out = resolve(app, "core/resources/src/commonMain/kotlin/app/kiddo/core/resources/generated/BrandLogos.kt");
const named = { gold: "#FFD700" };

const attr = (tag, name) => tag.match(new RegExp(`[ \\t\\n]${name}="([^"]*)"`))?.[1];
const argb = (hex, opacity = 1) => {
  const h = (named[hex] ?? hex).replace("#", "");
  const full = h.length === 3 ? [...h].map((c) => c + c).join("") : h;
  const a = Math.round(opacity * 255).toString(16).padStart(2, "0");
  return `0x${a}${full}`.toUpperCase().replace("0X", "0x");
};
const camel = (s) => s.replace(/-color$/, "").replace(/-(\w)/g, (_, c) => c.toUpperCase());
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const kstr = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

const entries = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(resolve(dir, file), "utf8");
  const root = svg.match(/<svg[^>]*>/)[0];
  const [x, y, w, h] = attr(root, "viewBox").split(/\s+/).map(Number);
  const tint = attr(root, "fill") === "currentColor";
  const rootEvenOdd = attr(root, "fill-rule") === "evenodd";
  const gradients = {};
  for (const [, open, body] of svg.matchAll(/(<linearGradient[^>]*>)([\s\S]*?)<\/linearGradient>/g)) {
    const stops = [...body.matchAll(/<stop[^>]*>/g)].map(([s]) =>
      `${Number(attr(s, "offset") ?? 0)}f to ${argb(attr(s, "stop-color"), Number(attr(s, "stop-opacity") ?? 1))}`);
    const n = (k) => `${Number(attr(open, k))}f`;
    gradients[attr(open, "id")] = `LogoFill.Linear(${n("x1")}, ${n("y1")}, ${n("x2")}, ${n("y2")}, listOf(${stops.join(", ")}))`;
  }
  const paths = [...svg.matchAll(/<path[^>]*>/g)].map(([p]) => {
    const fill = attr(p, "fill");
    const ref = fill?.match(/url\(#(.+)\)/)?.[1];
    const kind = ref ? gradients[ref] : fill ? `LogoFill.Solid(${argb(fill)})` : tint ? "LogoFill.Tint" : "LogoFill.Solid(0xFF000000)";
    const evenOdd = (attr(p, "fill-rule") ?? (rootEvenOdd ? "evenodd" : "nonzero")) === "evenodd";
    return `LogoPath(${kstr(normalizePath(attr(p, "d")))}, ${kind}, evenOdd = ${evenOdd})`;
  });
  entries.push(`    ${pascal(camel(basename(file, ".svg")))}(\n        ${x}f, ${y}f, ${w}f, ${h}f,\n        listOf(\n${paths.map((p) => `            ${p},`).join("\n")}\n        ),\n    ),`);
}

const kotlin = `// Generated by tools/logos/generate.mjs. Do not edit by hand. Each logo belongs to its owner.
package app.kiddo.core.resources.generated

public sealed interface LogoFill {
    public data object Tint : LogoFill

    public class Solid(public val argb: Long) : LogoFill

    public class Linear(
        public val x1: Float,
        public val y1: Float,
        public val x2: Float,
        public val y2: Float,
        public val stops: List<Pair<Float, Long>>,
    ) : LogoFill
}

public class LogoPath(public val pathData: String, public val fill: LogoFill, public val evenOdd: Boolean)

public enum class BrandLogo(
    public val x: Float,
    public val y: Float,
    public val width: Float,
    public val height: Float,
    public val paths: List<LogoPath>,
) {
${entries.join("\n")}
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, kotlin);
console.log(`${entries.length} logos -> ${out}`);
